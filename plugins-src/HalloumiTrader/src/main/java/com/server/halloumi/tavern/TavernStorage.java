package com.server.halloumi.tavern;

import com.server.halloumi.model.Tavern;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.List;
import java.util.logging.Logger;

/**
 * Persistence for {@code taverns.txt} with tolerant per-line parsing.
 */
public final class TavernStorage {

    private static final String HEADER = "# world,x,y,z,decorated,state (inn = built, inn-pending = not built yet,"
            + " none/east/west = old one to tear down) — generated by HalloumiTrader, one tavern per line";

    private final File file;
    private final Logger logger;

    public TavernStorage(File file, Logger logger) {
        this.file = file;
        this.logger = logger;
    }

    public List<Tavern> load() {
        List<Tavern> result = new ArrayList<>();
        if (!file.exists()) {
            return result;
        }
        try {
            List<String> lines = Files.readAllLines(file.toPath(), StandardCharsets.UTF_8);
            for (int i = 0; i < lines.size(); i++) {
                String line = lines.get(i).trim();
                if (line.isEmpty() || line.startsWith("#")) {
                    continue;
                }
                try {
                    result.add(Tavern.parse(line));
                } catch (RuntimeException e) {
                    logger.warning("Skipping malformed line " + (i + 1) + " in taverns.txt: " + e.getMessage());
                }
            }
        } catch (IOException e) {
            logger.severe("Failed to read taverns.txt: " + e.getMessage());
        }
        return result;
    }

    public boolean save(List<Tavern> taverns) {
        List<String> lines = new ArrayList<>(taverns.size() + 1);
        lines.add(HEADER);
        taverns.forEach(t -> lines.add(t.serialize()));
        try {
            File parent = file.getParentFile();
            if (parent != null) {
                Files.createDirectories(parent.toPath());
            }
            Files.write(file.toPath(), lines, StandardCharsets.UTF_8);
            return true;
        } catch (IOException e) {
            logger.severe("Failed to write taverns.txt: " + e.getMessage());
            return false;
        }
    }
}

